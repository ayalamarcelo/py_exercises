primer_entero = int(input("Ingrese un nro entero: "))
segundo_entero = int(input("Ingrese otro nro entero: "))

print(f"La suma de ambos enteros es: {primer_entero + segundo_entero}")
print(f"La resta de ambos enteros es: {primer_entero - segundo_entero}")
print(f"La multiplicacion de ambos enteros es: {primer_entero * segundo_entero}")
print(f"La division de ambos enteros es: {primer_entero // segundo_entero}")
print(f"El resto de ambos enteros es: {primer_entero % segundo_entero}")